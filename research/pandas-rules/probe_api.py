def t(label, fn):
    with warnings.catch_warnings(record=True) as w:
        warnings.simplefilter("always")
        try:
            r = fn()
            status = "ok"
        except Exception as e:
            r = None
            status = f"RAISES {type(e).__name__}: {str(e)[:110]}"
    ws = "; ".join(f"{x.category.__name__}: {str(x.message)[:120]}" for x in w)
    print(f"- {label}: {status}" + (f" | WARN {ws}" if ws else ""))
    return r

